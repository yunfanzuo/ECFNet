def get_ch_name(dataset, graph_type):
    """获取通道名列表
    Args:
        dataset (str): 数据集名称
        graph_type (str): 图类型
    Returns:
        list[str]: 通道名列表
    Notes:
        不进行区域划分，所有通道按序展开到一个列表中
    """
    if dataset not in channel:
        raise NotImplementedError(f"不支持的数据集: {dataset}")
    _channel = channel[dataset]
    if graph_type == "original":
        return _channel['original']
    elif graph_type in _channel:
        all_chs = _channel[graph_type]
        if len(all_chs) == 0 or isinstance(all_chs[0], str):
            return list(all_chs)
        return [ch for local_chs in all_chs for ch in local_chs]
    else:
        raise ValueError(f"不支持的图类型: {graph_type}")


def get_ch_index(dataset, graph_type):
    """获取通道相对原始通道图的位置索引
    Args:
        dataset (str): 数据集名称
        graph_type (str): 图类型
    Returns:
        list[int]: 通道相对位置索引
    Notes:
        不进行区域划分，所有通道索引按序展开到一个列表中
    """
    if dataset not in channel:
        raise NotImplementedError(f"不支持的数据集: {dataset}")
    _channel = channel[dataset]
    raw_chs = _channel['original']
    if graph_type == "original":
        return list(range(len(raw_chs)))
    elif graph_type in _channel:
        graph_chs = _channel[graph_type]
        if len(graph_chs) == 0 or isinstance(graph_chs[0], str):
            return [raw_chs.index(ch) for ch in graph_chs]
        return [raw_chs.index(ch) for local_chs in graph_chs for ch in local_chs]
    else:
        raise ValueError(f"不支持的图类型: {graph_type}")


def get_local_ch_num(dataset, graph_type):
    """获取每个局部区域的通道数
    Args:
        dataset (str): 数据集名称
        graph_type (str): 图类型
    Returns:
        list[int]: 每个局部区域的通道数
    """
    if dataset not in channel:
        raise NotImplementedError(f"不支持的数据集: {dataset}")
    _channel = channel[dataset]
    if graph_type == "original":
        all_chs = _channel['original']
        return [1] * len(all_chs)
    elif graph_type in _channel:
        all_chs = _channel[graph_type]
        if len(all_chs) == 0 or isinstance(all_chs[0], str):
            return [1] * len(all_chs)
        return [len(local_chs) for local_chs in all_chs]
    else:
        raise ValueError(f"不支持的图类型: {graph_type}")


def channel_reindex(dataset, graph_type):
    """通道重索引
    Args:
        dataset (str): 数据集名称
        graph_type (str): 图类型
    Returns:
        tuple[list[str], list[int], list[int]]: 通道名列表, 通道相对位置索引列表, 每个局部区域的通道数
    """
    return (
        get_ch_name(dataset, graph_type),
        get_ch_index(dataset, graph_type),
        get_local_ch_num(dataset, graph_type)
    )
